#!/usr/bin/env node
// Deterministic generator for the AI-native docs structural regions.
//
// It rewrites ONLY the text between the explicit marker comments in
// docs/ai-native/*.md, so hand-written / agent-written prose outside the
// markers is never touched. No network, no LLM, Node built-ins only, so it
// is safe to run from a git hook on every commit.
//
// Markers (one section per pair):
//   <!-- ai-native:auto:START section=structure --> ... <!-- ai-native:auto:END -->
//
// Only the structure region is generated (DEC-0023). The recent-history region
// was removed because per-branch git-log content conflicted on every PR.
//
// Design rules followed (see docs/ai-native/decision.md):
//  - idempotent and clone-independent: the tree is built from tracked files
//    (`git ls-files`), never the disk, so untracked local folders cannot leak in.
//  - cross-platform: path.sep handling, '\n' output, no shell globbing.
//  - bounded: capped tree depth and capped children per dir.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(SCRIPT_DIR, '..', '..');
const DOC_DIR = join(REPO_ROOT, 'docs', 'ai-native');

// --- bounds (coding-standards rule 1 & 8) ---
const MAX_DEPTH = 2; // top-level dirs + one level in
const MAX_CHILDREN = 40; // per directory, then an elision line
const GIT_TIMEOUT_MS = 15000;

// Generated / vendor directories pruned from the tree.
const EXCLUDE_DIRS = new Set([
  'node_modules', 'dist', 'dist-ssr', 'build', 'coverage',
  '.dart_tool', '.pub-cache', '.pub', '.gradle', 'Pods',
  '.next', 'out', '.turbo', '.vite', '.cache', '.parcel-cache',
  '.svelte-kit', '.output', '.venv', '__pycache__',
]);

// Known subsystems and their one-line purpose. A row is emitted only when the
// directory exists, so the map drops stale entries automatically.
const SUBSYSTEMS = [
  { path: 'src', label: 'Web frontend', purpose: 'React 18 + Vite + TypeScript UI (record/upload, MSAL auth, Supabase data).' },
  { path: 'workflow-server', label: 'Backend + MCP', purpose: 'Node HTTP backend: transcribe/summarize pipeline (AssemblyAI + Gemini); also hosts the MCP server, knowledge extraction, memory, and speaker-ID.' },
  { path: 'supabase', label: 'Data + edge', purpose: 'Postgres schema + migrations, RLS, and Deno edge functions (token exchange, audio URLs, profile generation, admin).' },
  { path: 'meeting-note-mobile', label: 'Mobile app', purpose: 'Flutter / Dart app (core / features / shared under app/lib).' },
  { path: 'product-page', label: 'Product page', purpose: 'Static product / marketing landing page.' },
  { path: 'scripts', label: 'Repo scripts', purpose: 'Root build, version-stamp, QA, and AI-native-docs helper scripts.' },
];

const MARK_START = (section) => `<!-- ai-native:auto:START section=${section} -->`;
const MARK_END = '<!-- ai-native:auto:END -->';
const AUTO_NOTE = '<!-- Generated by scripts/ai-native-docs/generate.mjs. Do not edit inside this region; run `npm run docs:ai-native`. -->';

/** Tracked file paths (repo-relative, '/' separated), from the git index. */
function readTrackedFiles(root) {
  const stdout = execFileSync('git', ['ls-files', '-z'], {
    cwd: root,
    encoding: 'utf8',
    timeout: GIT_TIMEOUT_MS,
    maxBuffer: 64 * 1024 * 1024,
  });
  return stdout.split('\0').filter(Boolean);
}

/** Nested Map of directory names derived from tracked file paths. */
function buildDirTree(files) {
  const root = new Map();
  for (const file of files) {
    const parts = file.split('/').slice(0, -1);
    let node = root;
    for (const name of parts) {
      if (name.startsWith('.') || EXCLUDE_DIRS.has(name)) break;
      if (!node.has(name)) node.set(name, new Map());
      node = node.get(name);
    }
  }
  return root;
}

function sortedNames(node) {
  return [...node.keys()].sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase()));
}

/** Recursive, depth- and width-bounded directory tree as markdown lines. */
function walkTree(node, prefix, depth, out) {
  if (depth > MAX_DEPTH) return;
  const names = sortedNames(node);
  const shown = names.slice(0, MAX_CHILDREN);
  shown.forEach((name, i) => {
    const last = i === shown.length - 1 && names.length <= MAX_CHILDREN;
    const branch = last ? '└── ' : '├── ';
    out.push(`${prefix}${branch}${name}/`);
    const nextPrefix = prefix + (last ? '    ' : '│   ');
    walkTree(node.get(name), nextPrefix, depth + 1, out);
  });
  if (names.length > MAX_CHILDREN) {
    out.push(`${prefix}└── … (${names.length - MAX_CHILDREN} more)`);
  }
}

/** Structure region text for a list of tracked file paths. Pure and deterministic. */
export function buildStructureRegion(files) {
  const dirTree = buildDirTree(files);
  const tree = ['.'];
  walkTree(dirTree, '', 1, tree);

  const rows = SUBSYSTEMS
    .filter((s) => dirTree.has(s.path))
    .map((s) => `| \`${s.path}/\` | ${s.label} | ${s.purpose} |`);

  const lines = [
    AUTO_NOTE,
    '',
    '### Repository structure',
    '',
    `Tracked directories only, to depth ${MAX_DEPTH}; generated / vendor directories (node_modules, dist, build, coverage, .dart_tool, and similar) are pruned.`,
    '',
    '```text',
    ...tree,
    '```',
    '',
    '### Subsystem map',
    '',
    '| Path | Subsystem | Purpose |',
    '| --- | --- | --- |',
    ...rows,
  ];
  return lines.join('\n');
}

/** Replace the inner text of one marked region. Fails loud if markers missing. */
export function replaceRegion(content, section, inner) {
  const start = MARK_START(section);
  const startIdx = content.indexOf(start);
  if (startIdx === -1) {
    throw new Error(`marker not found: ${start}`);
  }
  const afterStart = startIdx + start.length;
  const endIdx = content.indexOf(MARK_END, afterStart);
  if (endIdx === -1) {
    throw new Error(`closing marker not found after ${start}`);
  }
  const before = content.slice(0, afterStart);
  const after = content.slice(endIdx);
  return `${before}\n${inner}\n${after}`;
}

/** Rewrite one doc file's regions; return true if the bytes changed. */
function updateDoc(fileName, sections) {
  const filePath = join(DOC_DIR, fileName);
  let content;
  try {
    content = readFileSync(filePath, 'utf8');
  } catch (err) {
    throw new Error(`cannot read ${fileName}: ${err.message}`);
  }
  let next = content;
  for (const [section, inner] of Object.entries(sections)) {
    next = replaceRegion(next, section, inner);
  }
  if (next === content) return false;
  writeFileSync(filePath, next);
  return true;
}

function main() {
  const changed = [];
  const structure = buildStructureRegion(readTrackedFiles(REPO_ROOT));
  if (updateDoc('intro.md', { structure })) changed.push('intro.md');

  if (changed.length === 0) {
    process.stdout.write('ai-native-docs: up to date.\n');
  } else {
    process.stdout.write(`ai-native-docs: regenerated ${changed.join(', ')}.\n`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    main();
  } catch (err) {
    // Surface clearly, but exit non-zero so a human run notices. The git hook
    // deliberately ignores this exit code so doc generation never blocks a commit.
    process.stderr.write(`ai-native-docs: ${err.message}
`);
    process.exit(1);
  }
}
