/// Resolves a string id to text in the current app language. Falls back to English, then to
/// the key itself, so a missing translation is visible but never crashes.
class AppText {
  const AppText(this.language);

  final AppLanguage language;

  String call(String key) =>
      _appStrings[key]?[language.code] ?? _appStrings[key]?['en'] ?? key;
}

/// Watch this to get the current-language translator; rebuilds when the language changes.
final appTextProvider =
    Provider<AppText>((ref) => AppText(ref.watch(appLanguageProvider)));
