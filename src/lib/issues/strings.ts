export const ISSUE_STRINGS: Record<AppLanguage, IssueStrings> = { ko, en };

/** ERR-1 + ERR-2: "{action} 실패: {raw}" plus the migration hint for schema errors. */
export function operationError(s: IssueStrings, action: string, error: unknown): string {
  const raw = error instanceof Error ? error.message : String(error);
  const code = (error as { code?: unknown })?.code;
  if (code === 'NO_ROW') return `${action}: ${s.noRowHint}`;
  const schemaMissing = /could not find|does not exist|schema cache|column .* not found/i.test(raw)
    || ['PGRST202', 'PGRST204', 'PGRST205', '42P01', '42883', '42703'].includes(String(code ?? ''));
  return `${action}: ${raw}${schemaMissing ? s.migrationHint : ''}`;
}
